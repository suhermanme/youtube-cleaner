from __future__ import annotations

from urllib.parse import quote

from playwright.sync_api import Page

YOUTUBE_HOME = "https://www.youtube.com/"
LIKED_VIDEOS = "https://www.youtube.com/playlist?list=LL"
WATCH_LATER = "https://www.youtube.com/playlist?list=WL"
PLAYLISTS = "https://www.youtube.com/feed/playlists"

# YouTube-owned collections can be rendered alongside normal playlist cards,
# but they are not ordinary playlists that a user can delete or remove from
# their Library. YS is the current desktop ID for "Saved Shorts".
YOUTUBE_MANAGED_COLLECTION_IDS = frozenset({"LL", "WL", "SS", "YS"})


def is_youtube_managed_collection(playlist_id: str) -> bool:
    return playlist_id in YOUTUBE_MANAGED_COLLECTION_IDS


def is_youtube_generated_playlist(playlist_id: str) -> bool:
    """Return whether a playlist is generated by YouTube, not user-owned."""
    return playlist_id.startswith(("OLAK5uy_", "RD"))


def playlist_url(playlist_id: str) -> str:
    return f"https://www.youtube.com/playlist?list={quote(playlist_id, safe='')}"


def navigate(page: Page, url: str) -> None:
    page.goto(url, wait_until="domcontentloaded")
    page.wait_for_timeout(500)
